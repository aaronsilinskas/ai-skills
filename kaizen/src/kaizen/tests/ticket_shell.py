def issue_json(**fields: object) -> str:
    """A ``gh issue view --json`` reply for an open issue with no labels, assignees, body or
    comments, with *fields* replacing those defaults."""
    issue: dict[str, object] = {
        "number": 7,
        "title": "T",
        "state": "OPEN",
        "stateReason": "",
        "labels": [],
        "assignees": [],
        "body": "",
        "comments": [],
        "url": "https://github.com/owner/proto/issues/7",
    }
    return json.dumps(issue | fields)


def sub_issue_json(
    number: int,
    state: str = "open",
    state_reason: str | None = None,
    labels: tuple[str, ...] = (),
    assignees: tuple[str, ...] = (),
) -> str:
    """One line of the sub-issues reply ``spec_sub_issues`` reads, titled ``T<number>``."""
    issue = {
        "number": number,
        "title": f"T{number}",
        "state": state,
        "state_reason": state_reason,
        "labels": list(labels),
        "assignees": list(assignees),
    }
    return json.dumps(issue) + "\n"


def proto_projects(tmp_path: Path, public: bool = True) -> Path:
    """A ``projects/`` directory under *tmp_path* registering one project, ``proto``, whose main
    checkout is ``tmp_path / "proto"``."""
    directory = tmp_path / "projects"
    directory.mkdir()
    visibility = str(public).lower()
    page = f"---\npath: {tmp_path / 'proto'}\ngithub: owner/proto\npublic: {visibility}\n---\n"
    (directory / "proto.md").write_text(page)
    return directory



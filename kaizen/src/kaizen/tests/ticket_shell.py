class Shell:
    """Records each argv and answers queries from canned replies.

    *answers* maps a run of consecutive words (such as ``("issue", "view")``) to the
    reply for any command containing it: a string is returned as stdout, an exception
    is raised, and a callable is called with the argv and its result returned. The first
    matching key wins; unmatched commands return ``""``.
    """

    def __init__(self, answers: Mapping[tuple[str, ...], Reply]) -> None:
        self.calls: list[list[str]] = []
        self._answers = answers

    def __call__(self, cmd: list[str]) -> str:
        self.calls.append(cmd)
        for words, reply in self._answers.items():
            if _contains(cmd, words):
                if isinstance(reply, BaseException):
                    raise reply
                return reply if isinstance(reply, str) else reply(cmd)
        return ""

    def ran(self, *words: str) -> list[list[str]]:
        """Every recorded command containing *words* consecutively."""
        return [cmd for cmd in self.calls if _contains(cmd, words)]


def failed(cmd: str, stderr: str = "") -> subprocess.CalledProcessError:
    """The error the real runner raises when *cmd* exits non-zero."""
    return subprocess.CalledProcessError(1, cmd.split(), output="", stderr=stderr)


def _contains(cmd: list[str], words: tuple[str, ...]) -> bool:
    n = len(words)
    return any(tuple(cmd[i : i + n]) == words for i in range(len(cmd) - n + 1))


class ShipShell(Shell):
    """A ``Shell`` whose ``gh pr create`` opens *new_pr*, and which also keeps each body file
    ``gh pr create`` or ``gh pr edit`` was given, and its text. A reply in *answers* replaces
    either."""

    def __init__(self, new_pr: str, answers: Mapping[tuple[str, ...], Reply]) -> None:
        super().__init__({("pr", "create"): self._create, ("pr", "edit"): self._edit, **answers})
        self.new_pr = new_pr
        self.body_files: list[Path] = []
        self.bodies: list[str] = []

    def _create(self, cmd: list[str]) -> str:
        self._keep_body(cmd)
        return f"{self.new_pr}\n"

    def _edit(self, cmd: list[str]) -> str:
        self._keep_body(cmd)
        return f"{cmd[cmd.index('edit') + 1]}\n"

    def _keep_body(self, cmd: list[str]) -> None:
        body_file = Path(cmd[cmd.index("--body-file") + 1])
        self.body_files.append(body_file)
        self.bodies.append(body_file.read_text())


